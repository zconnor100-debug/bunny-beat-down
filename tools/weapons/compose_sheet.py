#!/usr/bin/env python3
"""Compose preview contact sheets from the tiles written by blender/render_preview.py.

Each asset becomes a card: a 2 x 2 block (scale shot next to a 1 m capsule +
three turnaround views) under a header with id, triangle count, size and
markers. System python + Pillow (no numpy needed).
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

BG = (34, 37, 41)
CARD = (48, 52, 58)
TILE_BG_TOP = (104, 112, 120)
TILE_BG_BOTTOM = (70, 76, 84)
TEXT = (236, 232, 224)
SUB = (170, 176, 182)
ACCENT = (232, 120, 32)


def _font(size, bold=False):
    names = ["DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"]
    for base in ("/usr/share/fonts/truetype/dejavu", "/usr/share/fonts/TTF"):
        for n in names:
            p = Path(base) / n
            if p.exists():
                return ImageFont.truetype(str(p), size)
    return ImageFont.load_default()


def _gradient(w, h):
    img = Image.new("RGB", (w, h))
    d = ImageDraw.Draw(img)
    for y in range(h):
        t = y / max(1, h - 1)
        c = tuple(int(a + (b - a) * t) for a, b in zip(TILE_BG_TOP, TILE_BG_BOTTOM))
        d.line([(0, y), (w, y)], fill=c)
    return img


def _tile(path: Path, size: int, label: str | None = None):
    bg = _gradient(size, size).convert("RGBA")
    if path.exists():
        im = Image.open(path).convert("RGBA")
        im.thumbnail((size, size), Image.LANCZOS)
        bg.alpha_composite(im, ((size - im.width) // 2, (size - im.height) // 2))
    if label:
        d = ImageDraw.Draw(bg)
        d.text((8, size - 22), label, fill=SUB, font=_font(13))
    return bg.convert("RGB")


def card(asset_id: str, tiles_dir: Path, report: dict, tile=300):
    head = 82
    w = tile * 2
    img = Image.new("RGB", (w, head + tile * 2), CARD)
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, w, 4], fill=ACCENT)
    d.text((12, 10), asset_id, fill=TEXT, font=_font(20, True))
    size = report.get("size_m", [0, 0, 0])
    line = f"{report.get('tris_total', 0):,} tris   {size[0]:.2f} x {size[1]:.2f} x {size[2]:.2f} m   " \
           f"{report.get('texture_px', 0)} px"
    d.text((12, 38), line, fill=SUB, font=_font(14))
    mk = ", ".join(report.get("markers", {}).keys()) or ""
    nodes = [n for n in report.get("nodes", {}) if n != asset_id]
    extra = " | ".join(x for x in (mk, ("nodes: " + ", ".join(nodes)) if nodes else "") if x)
    if extra:
        d.text((12, 60), extra, fill=ACCENT, font=_font(13))
    names = [("scale", "next to 1 m capsule"), ("v1", "side"), ("v2", "front 3/4"), ("v3", "rear 3/4")]
    for k, (suffix, label) in enumerate(names):
        t = _tile(tiles_dir / f"{asset_id}_{suffix}.png", tile, label)
        img.paste(t, ((k % 2) * tile, head + (k // 2) * tile))
    return img


def sheet(title: str, ids: list[str], tiles_dir: Path, build_dir: Path, out: Path, cols=3, tile=300):
    cards = []
    for i in ids:
        rp = build_dir / f"{i}.json"
        rep = json.loads(rp.read_text()) if rp.exists() else {}
        cards.append(card(i, tiles_dir, rep, tile))
    gap, top = 16, 70
    cw, ch = cards[0].size
    rows = (len(cards) + cols - 1) // cols
    W = cols * cw + (cols + 1) * gap
    H = top + rows * ch + (rows + 1) * gap
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    d.text((gap, 18), title, fill=TEXT, font=_font(28, True))
    d.text((gap + d.textlength(title, font=_font(28, True)) + 18, 30),
           "generated by tools/weapons (Blender 5.2, Cycles bake) - grey capsule = 1 m", fill=SUB, font=_font(15))
    for k, c in enumerate(cards):
        x = gap + (k % cols) * (cw + gap)
        y = top + gap + (k // cols) * (ch + gap)
        img.paste(c, (x, y))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, optimize=True)
    return out


def closeup(title: str, paths: list[Path], out: Path, tile=640):
    head = 56
    img = Image.new("RGB", (tile * 2, head + tile * ((len(paths) + 1) // 2)), BG)
    d = ImageDraw.Draw(img)
    d.text((14, 14), title, fill=TEXT, font=_font(24, True))
    for k, p in enumerate(paths):
        img.paste(_tile(p, tile), ((k % 2) * tile, head + (k // 2) * tile))
    img.save(out, optimize=True)
    return out
