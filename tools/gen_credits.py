#!/usr/bin/env python3
"""Render CREDITS.md from assets/credits/*.json.

The in-game Credits screen (src/ui/credits_panel.gd) reads the same JSON files,
so the repository credits and the game credits are always identical.

    python3 tools/gen_credits.py            # writes CREDITS.md
    python3 tools/gen_credits.py --check    # exit 1 if CREDITS.md is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CREDITS_DIR = ROOT / "assets" / "credits"
OUT = ROOT / "CREDITS.md"
SECTIONS = {
    "characters": "Critters",
    "environment": "The Island",
    "weapons_props": "Carrot Guns & Props",
    "audio": "Sound & Music",
    "fonts": "Fonts",
    "project": "Project-made assets",
}


def esc(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def link(text: str, url: str) -> str:
    return f"[{esc(text)}]({url})" if url else esc(text)


def render() -> str:
    files = sorted(CREDITS_DIR.glob("*.json"),
                   key=lambda p: list(SECTIONS).index(p.stem) if p.stem in SECTIONS else 99)
    lines = [
        "# Credits",
        "",
        "Bunny Beat Down's code is original work under the MIT license (see `LICENSE`).",
        "Every third-party asset is listed below with its author, source and license,",
        "including CC0 assets that do not legally require it. The same list is shown",
        "in-game under **Main menu → Credits**.",
        "",
        "This file is generated by `tools/gen_credits.py` from `assets/credits/*.json`; edit the JSON, not this file.",
        "",
        "Built with [Godot Engine](https://godotengine.org) (MIT). Godot's own third-party",
        "notices are available in-game under Credits → Engine licenses.",
        "",
    ]
    for f in files:
        entries = json.loads(f.read_text())
        lines += [f"## {SECTIONS.get(f.stem, f.stem.replace('_', ' ').title())}", "",
                  "| Asset | Author | License | Used for | Changes |",
                  "|---|---|---|---|---|"]
        for e in entries:
            asset = link(e.get("asset", "?"), e.get("source_url", ""))
            author = link(e.get("author", ""), e.get("author_url", ""))
            lic = link(e.get("license", ""), e.get("license_url", ""))
            used = esc(e.get("used_for", ""))
            for extra in ("attribution", "note"):
                if e.get(extra):
                    used += f"<br>*{esc(e[extra])}*"
            lines.append(f"| {asset} | {author} | {lic} | {used} | {esc(e.get('changes', ''))} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("CREDITS.md is out of date — run tools/gen_credits.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
